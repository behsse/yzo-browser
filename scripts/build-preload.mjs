// Builds electron/preload.generated.cjs, the preload actually loaded by the UI window.
//
// The UI preload runs sandboxed, where `require` only reaches Electron's built-in modules, so it
// cannot load files from node_modules. This script inlines electron-chrome-extensions'
// browser-action module (which only requires "electron") in front of electron/preload.cjs and then
// injects the <browser-action-list> element used to show extension icons.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);

const browserAction = readFileSync(require.resolve("electron-chrome-extensions/browser-action"), "utf8");
const preload = readFileSync(join(root, "electron", "preload.cjs"), "utf8");

const output = `// GENERATED by scripts/build-preload.mjs — do not edit. Source: electron/preload.cjs.
const __browserActionModule = (() => {
  const module = { exports: {} };
  ((module, exports, require) => {
${browserAction}
  })(module, module.exports, require);
  return module.exports;
})();

${preload}
__browserActionModule.injectBrowserAction();
`;

writeFileSync(join(root, "electron", "preload.generated.cjs"), output);
console.log("electron/preload.generated.cjs written");
